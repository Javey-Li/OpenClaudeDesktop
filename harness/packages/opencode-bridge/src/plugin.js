/**
 * The OpenCode plugin the bridge installs in its generated config folder
 * (<config>/plugin/code-desktop.js; OpenCode and MiMo load plugin/*.js from
 * every config folder). It is the per-session customization channel the
 * HTTP API lacks. The bridge writes one JSON file per session under
 * <state>/runtime/sessions/<id>.json (index.js sessionRuntime):
 *   { root, cwd, systemPrompt, instructions, modelParams, sandbox: {mode, roots, network} }
 * and the plugin reads it at every hook, so a change applies from the next step:
 *
 *   chat.message                       waits (≤10 s) for the session's file, so a sub-agent's
 *                                      first step never runs before the bridge configured it
 *   experimental.chat.system.transform a custom system prompt replaces the whole assembled
 *                                      prompt ({{model}}, {{provider}}, {{cwd}} filled in);
 *                                      project instructions are appended after it; the
 *                                      default and final prompt are recorded for the preview
 *   session.llm.request (MiMo)         records MiMo's final prompt (it appends its skill
 *                                      catalog and instruction files after the transform)
 *   chat.params                        per-model temperature / max output tokens
 *   shell.env                          the sandbox profile for the session's shell commands
 *   tool.execute.before (MiMo)         the edit guard: in a read-only mode (editGuard set), a
 *                                      file edit outside the plan folders is cancelled, even in a
 *                                      prompt loop that started under a mode that allowed edits
 *   tool.execute.before                a call of Code Desktop's own tools (appTools: {prefix, session})
 *                                      gets the app thread as its __code_desktop_session argument
 *                                      (MiMo runs the hook's args: a copy, so the stored input the
 *                                      model sees again keeps none; OpenCode runs the args object it
 *                                      stores, so it is added there)
 *   tool.execute.after                 drops it from that object again once the server has it
 *   experimental.chat.messages.transform
 *                                      the argument never reaches the model: OpenCode saves the call's input while it
 *                                      runs (a copy that keeps it) and reads the next step's history from that copy, so
 *                                      every step's (and a compaction's) history drops it from Code Desktop's own tools'
 *                                      calls; each prompt then reads the same from its first step on (a provider's
 *                                      prompt cache keeps the prefix), whenever the stored copy is cleaned
 *
 * The plugin has no imports beyond node:fs/node:path (no npm install needed).
 */
import { seatbeltProfile } from './sandbox.js'
import { SESSION_ARG } from './app-tools.js'

export const PLUGIN_FILE = 'code-desktop.js'

/** @param {{ replaceArgs?: boolean }} [options] replaceArgs: the agent runs tool.execute.before's output.args (MiMo). */
export function pluginSource({ replaceArgs = false } = {}) {
  return `// Generated by Code Desktop (harness/packages/opencode-bridge/src/plugin.js). Do not edit.
import fs from "node:fs"
import path from "node:path"

const STATE = process.env.CODE_DESKTOP_OPENCODE_STATE || ""
const REPLACE_ARGS = ${replaceArgs === true}
const safe = (id) => String(id).replace(/[^A-Za-z0-9_-]/g, "_")
const file = (kind, id) => path.join(STATE, "runtime", kind, safe(id) + ".json")
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms))
function read(id) {
  if (!STATE || !id) return null
  try { return JSON.parse(fs.readFileSync(file("sessions", id), "utf8")) } catch { return null }
}
async function waitFor(id, ms) {
  const end = Date.now() + ms
  for (;;) {
    const value = read(id)
    if (value || Date.now() > end) return value
    await sleep(40)
  }
}
function write(kind, id, value) {
  if (!STATE || !id) return
  try {
    fs.mkdirSync(path.join(STATE, "runtime", kind), { recursive: true })
    const target = file(kind, id)
    fs.writeFileSync(target + ".tmp", JSON.stringify(value))
    fs.renameSync(target + ".tmp", target)
  } catch {}
}
function interpolate(text, vars) {
  return text.replace(/\\{\\{([a-z][a-z0-9_]*)\\}\\}/g, (match, name) => (typeof vars[name] === "string" ? vars[name] : match))
}
const seatbeltProfile = ${seatbeltProfile.toString()}
function paramsFor(table, model) {
  if (!table || typeof table !== "object" || !model) return undefined
  for (const key of [(model.providerID || "") + "/" + (model.id || model.modelID || ""), model.id, model.modelID, model.api && model.api.id]) {
    if (typeof key === "string" && Object.prototype.hasOwnProperty.call(table, key)) return table[key]
  }
  return undefined
}

const EDIT_TOOLS = new Set(["edit", "write", "apply_patch", "patch", "multiedit", "notebook_edit"])
// The files an edit tool call would change (absolute); an apply_patch names them in its headers.
function editTargets(args, cwd) {
  const out = []
  for (const key of ["filePath", "file_path", "path", "notebook_path"]) if (args && typeof args[key] === "string" && args[key]) out.push(args[key])
  const patch = args && (args.patchText || args.patch_text || args.patch)
  if (typeof patch === "string") {
    for (const line of patch.split("\\n")) {
      const match = /^\\*\\*\\* (?:Add File|Update File|Delete File|Move to): (.+)$/.exec(line.trim())
      if (match) out.push(match[1].trim())
    }
  }
  return out.map((file) => path.resolve(cwd || "/", file))
}
function inPlanFolder(file, guard) {
  if (guard.planSegment && file.includes(guard.planSegment)) return true
  return (guard.planDirs || []).some((dir) => file === dir || file.startsWith(dir + path.sep))
}

export const CodeDesktop = async () => ({
  "chat.message": async (input) => {
    if (input && input.sessionID) await waitFor(input.sessionID, 10000)
  },
  "experimental.chat.system.transform": async (input, output) => {
    const id = input && input.sessionID
    const config = read(id)
    const before = Array.isArray(output.system) ? output.system.slice() : []
    if (config && typeof config.systemPrompt === "string" && config.systemPrompt) {
      const model = input.model || {}
      const vars = { model: model.id || "", provider: model.providerID || "", cwd: config.cwd || "" }
      // Kept after the custom prompt: the runtime catalogs (available skills, MCP server
      // instructions), never OpenCode's own prose, environment block or instruction files.
      const all = before.join("\\n")
      const kept = []
      const mcp = all.match(/<mcp_instructions>[\\s\\S]*?<\\/mcp_instructions>/)
      if (mcp) kept.push(mcp[0])
      const skills = all.indexOf("Skills provide specialized instructions")
      if (skills >= 0) kept.push(all.slice(skills).split("\\n<mcp_instructions>")[0].trim())
      output.system.splice(0, output.system.length, [interpolate(config.systemPrompt, vars), ...kept].join("\\n\\n"))
    }
    if (config && typeof config.instructions === "string" && config.instructions) output.system.push(config.instructions)
    if (id) {
      const previous = (() => { try { return JSON.parse(fs.readFileSync(file("prompts", id), "utf8")) } catch { return {} } })()
      write("prompts", id, { ...previous, at: Date.now(), model: input.model ? (input.model.providerID || "") + "/" + (input.model.id || "") : null, default: before, final: output.system.slice(), custom: Boolean(config && config.systemPrompt) })
    }
  },
  "session.llm.request": async (input) => {
    const id = input && input.sessionID
    if (!id || !Array.isArray(input.systemPrompt)) return
    const previous = (() => { try { return JSON.parse(fs.readFileSync(file("prompts", id), "utf8")) } catch { return {} } })()
    write("prompts", id, { ...previous, sent: input.systemPrompt.slice(), sentAt: Date.now() })
  },
  "chat.params": async (input, output) => {
    const config = read(input && input.sessionID)
    const params = paramsFor(config && config.modelParams, input && input.model)
    if (!params) return
    if (typeof params.temperature === "number") output.temperature = params.temperature
    if (typeof params.maxTokens === "number") output.maxOutputTokens = params.maxTokens
  },
  "tool.execute.before": async (input, output) => {
    // Code Desktop's own tools (one server for every session): the call names its app thread, an argument the
    // server strips. A session without it (a side question) names none, and the app refuses the call.
    if (input && output && typeof input.tool === "string" && output.args && typeof output.args === "object") {
      const tools = (read(input.sessionID) || {}).appTools
      if (tools && typeof tools.prefix === "string" && input.tool.startsWith(tools.prefix) && typeof tools.session === "string") {
        if (REPLACE_ARGS) output.args = { ...output.args, ${SESSION_ARG}: tools.session }
        else output.args.${SESSION_ARG} = tools.session
      }
    }
    if (!input || !EDIT_TOOLS.has(input.tool) || !output) return
    const config = read(input.sessionID)
    const guard = config && config.editGuard
    if (!guard) return
    const targets = editTargets(output.args, guard.cwd || config.cwd)
    if (targets.length && targets.every((file) => inPlanFolder(file, guard))) return
    output.cancel = true
    output.cancelReason = "This mode cannot change files."
  },
  "tool.execute.after": async (input) => {
    // The args object OpenCode ran the call with is the one it stores and shows the model again: the session argument
    // added above leaves it once the server has seen it (a copy of the part saved while the call ran can keep it).
    const args = input && input.args
    if (!args || typeof args !== "object" || typeof input.tool !== "string" || !(${JSON.stringify(SESSION_ARG)} in args)) return
    const tools = (read(input.sessionID) || {}).appTools
    if (tools && typeof tools.prefix === "string" && input.tool.startsWith(tools.prefix)) delete args[${JSON.stringify(SESSION_ARG)}]
  },
  "experimental.chat.messages.transform": async (input, output) => {
    const list = output && Array.isArray(output.messages) ? output.messages : []
    const prefixes = new Map()
    const prefixOf = (id) => {
      if (!id) return null
      if (!prefixes.has(id)) {
        const tools = (read(id) || {}).appTools
        prefixes.set(id, tools && typeof tools.prefix === "string" && tools.prefix ? tools.prefix : null)
      }
      return prefixes.get(id)
    }
    for (const message of list) {
      const parts = message && Array.isArray(message.parts) ? message.parts : null
      if (!parts) continue
      for (let index = 0; index < parts.length; index++) {
        const part = parts[index]
        const args = part && part.type === "tool" && part.state ? part.state.input : null
        if (!args || typeof args !== "object" || Array.isArray(args) || !(${JSON.stringify(SESSION_ARG)} in args) || typeof part.tool !== "string") continue
        const prefix = prefixOf(part.sessionID || (message.info && message.info.sessionID))
        if (!prefix || !part.tool.startsWith(prefix)) continue
        const clean = { ...args }
        delete clean[${JSON.stringify(SESSION_ARG)}]
        // A new part object: the history entries stay as OpenCode read them.
        parts[index] = { ...part, state: { ...part.state, input: clean } }
      }
    }
  },
  "shell.env": async (input, output) => {
    const id = input && input.sessionID
    const config = id ? await waitFor(id, 3000) : null
    const sandbox = config && config.sandbox
    if (sandbox && sandbox.mode === "danger-full-access") { output.env.CODE_DESKTOP_SANDBOX = "none"; return }
    output.env.CODE_DESKTOP_SANDBOX = sandbox ? sandbox.mode : "read-only"
    output.env.CODE_DESKTOP_SANDBOX_PROFILE = seatbeltProfile(sandbox || { mode: "read-only", network: false })
  },
})
`
}
