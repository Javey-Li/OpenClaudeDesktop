// Package the same independent CLI parser used by the Harness tool edge.
// Electron's application archive excludes node_modules, so this must be standalone.
import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { rolldown } from 'rolldown';

const root = path.resolve(import.meta.dirname, '..');
const workspace = path.dirname(root);
const vendor = path.join(workspace, 'vendor/deepseek-harness');
const target = path.join(root, 'third-party/codex-workflows-runner');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
for (const [relative, filename, manifestName] of [
  ['tool-workflow/src/claude-metadata.ts', 'claude-metadata.js', 'parser-build.json'],
  ['workflow-ptc/src/intrinsics.ts', 'workflow-intrinsics.js', 'intrinsics-build.json'],
  ['workflow-ptc/src/compiler.ts', 'workflow-compiler.js', 'compiler-build.json'],
  ['workflow-ptc/src/boundary.ts', 'workflow-boundary.js', 'boundary-build.json'],
  ['workflow-ptc/src/output.ts', 'workflow-output.js', 'output-build.json'],
  ['workflow-ptc/src/result.ts', 'workflow-result.js', 'result-build.json'],
]) {
const source = path.join(vendor, 'packages/workflow', relative);
const bundler = await rolldown({ input: source, platform: 'node', treeshake: { moduleSideEffects: false } });
try {
  const { output } = await bundler.generate({ format: 'esm', minify: false,
    banner: `// Generated by app/scripts/build-workflow-parser.mjs. See ../notices and ${manifestName}.` });
  if (output.length !== 1 || output[0].type !== 'chunk' || output[0].imports.length || output[0].dynamicImports.length)
    throw new Error('Workflow parser must be a single standalone module');
  const chunk = output[0];
  const sources = [];
  for (const file of Object.keys(chunk.modules).sort()) {
    if (file.startsWith('\0')) continue;
    sources.push({ path: path.relative(workspace, file), sha256: hash(await fs.readFile(file)) });
  }
  await fs.mkdir(path.join(target, 'notices'), { recursive: true });
  const require = createRequire(path.join(vendor, 'packages/workflow', relative.split('/')[0], 'package.json'));
  const dependencies = {};
  // Keep notices for both imported dependencies, including JSON5 when tree-shaken.
  for (const name of relative.startsWith('tool-workflow/') ? ['acorn', 'json5'] : relative.endsWith('compiler.ts') ? ['acorn', 'acorn-walk'] : []) {
    const manifest = require.resolve(`${name}/package.json`);
    dependencies[name] = JSON.parse(await fs.readFile(manifest, 'utf8')).version;
    await fs.copyFile(path.join(path.dirname(manifest), name === 'json5' ? 'LICENSE.md' : 'LICENSE'), path.join(target, 'notices', `${name}-LICENSE`));
  }
  await fs.copyFile(path.join(vendor, 'LICENSE'), path.join(target, 'notices', 'deepseek-harness-LICENSE'));
  await fs.writeFile(path.join(target, 'src', filename), chunk.code);
  await fs.writeFile(path.join(target, manifestName), JSON.stringify({
    output: `src/${filename}`, sha256: hash(chunk.code), dependencies, sources,
    builderSha256: hash(await fs.readFile(import.meta.filename)),
  }, null, 2) + '\n');
  console.log(`Built standalone Workflow ${filename} (${Buffer.byteLength(chunk.code)} bytes)`);
} finally { await bundler.close(); }
}
