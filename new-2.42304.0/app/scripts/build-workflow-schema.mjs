// Bundle the Harness validator for the packaged alternate runner, including Ajv.
import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
import {rolldown} from 'rolldown';

const workspace=path.resolve(import.meta.dirname,'../..');
const source=path.join(workspace,'vendor/deepseek-harness/packages/subagent/subagent/src/output-schema.ts');
const target=path.join(workspace,'app/third-party/codex-workflows-runner');
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const bundler=await rolldown({input:source,platform:'node',treeshake:{moduleSideEffects:false}});
try{
  const {output}=await bundler.generate({format:'esm',minify:false,banner:'// Generated by app/scripts/build-workflow-schema.mjs. See ../schema-build.json and ../notices.'});
  if(output.length!==1||output[0].type!=='chunk'||output[0].dynamicImports.length||output[0].imports.some(name=>name!=='node:module'))throw Error('Workflow schema must bundle all package dependencies');
  const chunk=output[0],sources=[];
  for(const file of Object.keys(chunk.modules).sort())if(!file.startsWith('\0'))sources.push({path:path.relative(workspace,file),sha256:hash(await fs.readFile(file))});
  const require=createRequire(source),ajvRequire=createRequire(require.resolve('ajv'));
  const dependencies={};
  await fs.mkdir(path.join(target,'notices'),{recursive:true});
  for(const name of ['ajv','fast-uri','fast-deep-equal','json-schema-traverse']){
    const manifest=ajvRequire.resolve(name+'/package.json'),directory=path.dirname(manifest);
    dependencies[name]=JSON.parse(await fs.readFile(manifest,'utf8')).version;
    const license=(await fs.readdir(directory)).find(name=>/^licen[cs]e(?:\.md|\.txt)?$/iu.test(name));
    if(!license)throw Error('Missing dependency license: '+name);
    await fs.copyFile(path.join(directory,license),path.join(target,'notices',name+'-LICENSE'));
  }
  await fs.copyFile(path.join(workspace,'vendor/deepseek-harness/LICENSE'),path.join(target,'notices/deepseek-harness-LICENSE'));
  await fs.writeFile(path.join(target,'src/workflow-schema.js'),chunk.code);
  await fs.writeFile(path.join(target,'schema-build.json'),JSON.stringify({output:'src/workflow-schema.js',sha256:hash(chunk.code),dependencies,sources,builderSha256:hash(await fs.readFile(import.meta.filename))},null,2)+'\n');
  console.log(`Built Workflow schema validator (${Buffer.byteLength(chunk.code)} bytes)`);
}finally{await bundler.close();}
