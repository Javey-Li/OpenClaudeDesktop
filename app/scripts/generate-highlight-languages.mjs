import fs from "node:fs/promises";
import path from "node:path";

// Regenerates src/highlight-languages.mjs (ids + aliases and the file-name
// maps, main-thread data) and src/highlight-grammar-loaders.mjs (one dynamic
// import per grammar, worker only) from the original bundledLanguagesInfo
// table (c5a058668, 235 ids) and file-name maps (c41eb0199, c8a544a8c); all
// read only. Every id must exist in the pinned @shikijs/langs exports map.
// Run: node scripts/generate-highlight-languages.mjs
const root = path.resolve(import.meta.dirname, "..");
const source = path.resolve(root, "../reference/current-2.2553.1/ion-dist/assets/v1/c5a058668-BzDsGvUV.js");
const text = await fs.readFile(source, "utf8");
const entries = [];
for (const match of text.matchAll(/\{id:"([^"]+)",name:"[^"]+",(?:aliases:\[([^\]]*)\],)?import/g))
  entries.push([match[1], ...(match[2] ? JSON.parse(`[${match[2]}]`) : [])]);
if (entries.length !== 235) throw new Error(`Expected 235 bundled languages, found ${entries.length}`);
const langs = JSON.parse(await fs.readFile(path.join(root, "node_modules/@shikijs/langs/package.json"), "utf8"));
for (const [id] of entries) if (!langs.exports[`./${id}`]) throw new Error(`@shikijs/langs ${langs.version} has no grammar ${id}`);
// The file-name maps of the original resolver (read only): `n` in c41eb0199
// (345 keys: a full name, a compound `.a.b` or a last extension -> language,
// resolved by r()) and the lockfile names g() checks first (c8a544a8c `t`,
// code-language-current.js:78-85). Both are plain {key:"value"} literals.
function objectLiteral(file, pattern) {
  const body = pattern.exec(file)?.[1];
  if (body === undefined) throw new Error(`No map literal for ${pattern}`);
  const map = [];
  const pair = /(?:"((?:[^"\\]|\\.)*)"|([A-Za-z_$][\w$]*)):"((?:[^"\\]|\\.)*)"(?:,|$)/y;
  for (let at = 0; at < body.length;) {
    pair.lastIndex = at;
    const match = pair.exec(body);
    if (!match) throw new Error(`Unparsed map entry at ${at}: ${body.slice(at, at + 40)}`);
    map.push([match[1] !== undefined ? JSON.parse(`"${match[1]}"`) : match[2], JSON.parse(`"${match[3]}"`)]);
    at = pair.lastIndex;
  }
  return map;
}
const extensions = objectLiteral(await fs.readFile(path.resolve(root, "../reference/current-2.2553.1/ion-dist/assets/v1/c41eb0199-C-RzbqEe.js"), "utf8"),
  /(?:^|[,;\s])n=\{([^}]*)\};function r\(/);
const lockfiles = objectLiteral(await fs.readFile(path.resolve(root, "../reference/current-2.2553.1/ion-dist/assets/v1/c8a544a8c-DRZSqxeJ.js"), "utf8"),
  /var t=\{([^}]*)\};function n\(/);
if (extensions.length !== 345) throw new Error(`Expected 345 file-name keys, found ${extensions.length}`);
// Every value must name a bundled grammar (id or alias) once lowercased, as
// normalizeLanguage (highlight-model.mjs) resolves it.
const known = new Set(entries.flat());
for (const [key, value] of [...extensions, ...lockfiles])
  if (!known.has(value.toLowerCase())) throw new Error(`${key} maps to ${value}, which is no bundled id or alias`);
const header = "// Generated by scripts/generate-highlight-languages.mjs from the original\n"
  + "// bundledLanguagesInfo (c5a058668-BzDsGvUV.js, 235 ids). Do not edit by hand.\n";
const literal = (map) => "Object.freeze({\n  __proto__: null,\n" + map.map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`).join("\n") + "\n})";
await fs.writeFile(path.join(root, "src/highlight-languages.mjs"), header
  + "// [id, ...aliases]; code-language-current.js:18-28 adds the extra aliases.\n"
  + "export const BUNDLED_LANGUAGES = Object.freeze([\n"
  + entries.map((entry) => `  ${JSON.stringify(entry)},`).join("\n") + "\n]);\n"
  + "// File name -> language: the original's `n` (c41eb0199-C-RzbqEe.js, 345 keys:\n"
  + "// exact names such as Dockerfile, compound `.a.b` keys such as component.ts,\n"
  + "// last extensions), resolved by fileHighlightLanguage (file-preview-model.mjs).\n"
  + `export const FILE_EXTENSION_LANGUAGES = ${literal(extensions)};\n`
  + "// Lowercased lockfile names checked before `n` (c8a544a8c-DRZSqxeJ.js `t`).\n"
  + `export const LOCKFILE_LANGUAGES = ${literal(lockfiles)};\n`);
await fs.writeFile(path.join(root, "src/highlight-grammar-loaders.mjs"), header
  + "// One literal dynamic import per grammar (the original's per-language\n"
  + "// `import` thunks), so Vite emits every grammar as its own lazy chunk in\n"
  + "// both syntax workers. Imported only by highlight-engine.mjs.\n"
  + "export const grammarLoaders = Object.freeze({\n  __proto__: null,\n"
  + entries.map(([id]) => `  ${JSON.stringify(id)}: () => import(${JSON.stringify(`@shikijs/langs/${id}`)}),`).join("\n") + "\n});\n");
console.log(`Wrote ${entries.length} grammars (${entries.reduce((sum, entry) => sum + entry.length - 1, 0)} aliases), ${extensions.length} file names and ${lockfiles.length} lockfiles`);
